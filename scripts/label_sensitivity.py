"""Extinction class-definition sensitivity (ADR-018 variants B/C, ADR-021): writes docs/verification/extinction_label_sensitivity.json
and the generated section docs/verification/extinction_label_sensitivity.md (no hand-copied numbers).
Usage: ``.venv/Scripts/python scripts/label_sensitivity.py``
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fif.models.features import model_table  # noqa: E402
from fif.validation.label_sensitivity import run  # noqa: E402

OUT = ROOT / "docs" / "verification"


def main() -> None:
    t = model_table(pd.read_csv(ROOT / "data" / "processed" / "flex.csv"))
    r = run(t)
    (OUT / "extinction_label_sensitivity.json").write_text(json.dumps(r, indent=1), encoding="utf-8")
    L = ["# Extinction label sensitivity (generated by scripts/label_sensitivity.py)\n",
         "Variants: A = from the extinction diameter (used, ADR-018); B = from 'Test end', Disruption excluded; "
         "C = from 'Test end', Disruption counted as no extinction. Grouped CV, 3 seeds, all extinction models.\n",
         "Rule fixed before running: " + r["rule"].replace("\n", " ") + "\n",
         "| Variant | n | positive / negative | agreement with A | " + " | ".join(f"AUC {m}" for m in r["variants"]["A_diameter"]["models"]) + " |",
         "|---|---|---|---|" + "---|" * len(r["variants"]["A_diameter"]["models"])]
    for name, v in r["variants"].items():
        L.append(f"| {name} | {v['n']} | {v['n_positive']} / {v['n_negative']} | {v['agreement_with_A']:.2f} (n {v['n_compared_with_A']}) | "
                 + " | ".join("n/a" if m == "prior" else f"{d['AUC']:.3f}" for m, d in v["models"].items()) + " |")
    L.append("\nInterface model (" + r["interface_model"] + ") refitted on each variant: P(extinction) at 1 atm, 3 mm\n")
    L.append("| Variant | methanol O2 0.15 | methanol O2 0.30 | heptane O2 0.15 | heptane O2 0.30 | worst rise of P along O2 |")
    L.append("|---|---|---|---|---|---|")
    for name, v in r["variants"].items():
        p = v["interface_P_at_O2"]
        L.append(f"| {name} | {p['Methanol']['P_O2_0.15']:.2f} | {p['Methanol']['P_O2_0.30']:.2f} | {p['Heptane']['P_O2_0.15']:.2f} | "
                 f"{p['Heptane']['P_O2_0.30']:.2f} | {v['interface_worst_P_rise_along_O2']:.3f} |")
    L.append("\nChecks: " + "; ".join(f"{k}: " + ", ".join(f"{c} {'pass' if ok else 'FAIL'}" for c, ok in v.items()) for k, v in r["checks"].items()))
    L.append(f"\n**Result: {'robust - the conclusions do not depend on the class definition' if r['robust'] else 'NOT robust - see the failed checks'}.**\n")
    (OUT / "extinction_label_sensitivity.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
