"""Compute all insights live, rank them (ADR-033: formula A) and write docs/insights.json + docs/INSIGHTS.md.

Usage: ``.venv/Scripts/python scripts/build_insights.py``. Every number in INSIGHTS.md comes from this run.
"""

from __future__ import annotations

import json
import sys
import warnings
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
warnings.filterwarnings("ignore")
from fif.insights import catalog as cat  # noqa: E402
from fif.insights.base import EVIDENCE_WEIGHTS, rank  # noqa: E402


def fmt_ci(e):
    if e.get("ci"):
        return f"{e['value']:.3g} [{e['ci'][0]:.3g}, {e['ci'][1]:.3g}]"
    return "n/a" if e.get("value") is None else f"{e['value']:.3g}"


def main():
    ins = cat.all_insights()
    ranked = rank([i for i in ins if i.stage in ("prevention", "detection", "suppression")])
    other = [i for i in ins if i.stage not in ("prevention", "detection", "suppression")]
    atm = cat.cabin_atmospheres()
    out = {
        "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "ranking": "A_evidence_log_n",
        "ranked": [i.to_dict() for i in ranked],
        "history_and_earth": [i.to_dict() for i in other],
        "cabin_atmospheres": atm.to_dict(orient="records"),
    }
    (ROOT / "docs" / "insights.json").write_text(json.dumps(out, indent=1, default=float), encoding="utf-8")

    L = [
        f"# Insights\n\nGenerated by `scripts/build_insights.py` ({out['created_utc']}) from live calculations in "
        "`src/fif/insights/catalog.py`; do not edit numbers by hand. Decisions: ADR-033 (catalog, ranking formula A, wording).\n",
        "## Ranking formula (ADR-033, docs/FORMULAS.md section 8)\n",
        "$$S = w_{type}\\cdot\\ln(1 + n_{tests})\\cdot(0.3 + 0.7\\,e), \\qquad e = \\min(|\\ln \\text{effect}|/0.5,\\ 1)$$\n",
        "Weights: "
        + ", ".join(f"{k} {v}" for k, v in EVIDENCE_WEIGHTS.items())
        + ". Insights without a ratio-type effect get e = 0. "
        "History and spinoff entries (n = 0) are not ranked; they form the 'Lessons from history' and 'Benefits on Earth' blocks.\n",
        "Data effects come from one regression of ln K (and ln d_ext/d0) on fuel, O2, ln p, CO2, He and ln d0 over the FLEX tests, "
        "with 95 % intervals from a bootstrap over test regimes (1000 resamples).\n",
        "## Ranked catalog\n",
        "| Rank | ID | Stage | Insight | Evidence | n | Effect [95 % CI] | Confidence | Score |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for k, i in enumerate(ranked, 1):
        L.append(
            f"| {k} | {i.id} | {i.stage} | {i.title}{' (extrapolation)' if i.extrapolation else ''} | {i.evidence_type} | "
            f"{i.n_tests} | {fmt_ci(i.effect)} | {i.confidence} | {i.score:.2f} |"
        )
    L.append("\n## Details\n")
    for i in ranked:
        L += [
            f"### {i.id}. {i.title}\n",
            f"- **Finding:** {i.finding}",
            f"- **Action:** {i.action}",
            f"- **Evidence:** {i.evidence_type}; n = {i.n_tests}; confidence {i.confidence}"
            + ("; extrapolation" if i.extrapolation else ""),
            f"- **Effect:** {i.effect['name']} = {fmt_ci(i.effect)}",
            f"- **Sources:** {'; '.join(i.sources)}" + (f"\n- **Linked:** {', '.join(i.related)}" if i.related else ""),
            "",
        ]
    L.append("## Lessons from history (NASA history, R2-R4)\n")
    for i in [x for x in other if x.stage == "history"]:
        L.append(f"- **{i.title}.** {i.finding} {i.action} Source: {i.sources[0]}")
    L.append("\n## Benefits on Earth (NASA spinoff, R5-R7)\n")
    for i in [x for x in other if x.stage == "earth"]:
        L.append(f"- **{i.title}.** {i.finding} {i.action} Source: {i.sources[0]}")
    L += [
        "\n## Cabin atmospheres (hybrid model, 3 mm droplet; model value withheld when unreliable)\n",
        "| Atmosphere | O2 | p, psi | Fuel | K hybrid, mm²/s | sigma ln K | K theory, mm²/s | Status | Reasons | Source |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in atm.to_dict(orient="records"):
        kh = (
            "withheld"
            if r["K_hybrid_mm2_s"] is None or r["K_hybrid_mm2_s"] != r["K_hybrid_mm2_s"]
            else f"{r['K_hybrid_mm2_s']:.3f}"
        )
        L.append(
            f"| {r['atmosphere']} | {r['O2']:.2f} | {r['p_psi']} | {r['fuel']} | {kh} | {r['sigma_ln']:.3f} | "
            f"{r['K_theory_mm2_s']:.3f} | {r['status']} | {r['reasons'] or '-'} | {r['source']} |"
        )
    L.append(
        "\nNo other cabin atmosphere (e.g. Orion/Artemis vehicles) is listed: no NASA source with its values was available to the project."
    )
    (ROOT / "docs" / "INSIGHTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("top 5:", [(i.id, i.title, round(i.score, 2)) for i in ranked[:5]])


if __name__ == "__main__":
    main()
