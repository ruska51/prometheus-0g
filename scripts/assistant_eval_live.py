"""Run the 10 evaluation questions through the DEPLOYED assistant (https://prometheus-0g.streamlit.app/assistant) in one
browser session and write docs/ASSISTANT_EVAL.md (stage 9, ADR-042). Uses the server's own Gemini key - no key on
this machine. Same questions and checks as scripts/assistant_eval.py; citations are read from the answer text and the
sources list the page shows (unknown ids are those cited in the text but not listed as sources).
Usage: ``python scripts/assistant_eval_live.py`` (needs Playwright + Microsoft Edge, requirements-dev.txt)
"""

from __future__ import annotations

import re
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from assistant_eval import NO_DATA, QUESTIONS  # noqa: E402

from fif.assistant.llm import SYSTEM, cited_ids  # noqa: E402

URL = "https://prometheus-0g.streamlit.app/assistant"


def app_frame(page):
    for _ in range(80):
        time.sleep(3)
        for f in page.frames:
            if f.locator("[data-testid=stChatInputTextArea]").count():
                return f
    raise RuntimeError("chat input not found")


def main() -> None:
    rows, details, model = [], [], "?"
    with sync_playwright() as p:
        b = p.chromium.launch(channel="msedge", headless=True)
        page = b.new_page(viewport={"width": 1400, "height": 2400})
        page.goto(URL, wait_until="domcontentloaded", timeout=240_000)
        fr = app_frame(page)
        for n, (qid, q, kind, exp) in enumerate(QUESTIONS, 1):
            t0 = time.time()
            inp = fr.locator("[data-testid=stChatInputTextArea]")
            inp.fill(q)
            inp.press("Enter")
            answer, err = "", ""
            for _ in range(60):
                time.sleep(3)
                msgs = fr.locator("[data-testid=stChatMessage]")
                alerts = [
                    a
                    for a in fr.locator("[data-testid=stAlert]").all_inner_texts()
                    if "Technical" in a or "unavailable" in a or "quota" in a or "could not" in a
                ]
                if msgs.count() >= 2 * n:
                    last = msgs.nth(2 * n - 1)
                    answer = last.locator("[data-testid=stMarkdownContainer]").first.inner_text()
                    exp_btn = last.locator("[data-testid=stExpander] summary")
                    if exp_btn.count():
                        exp_btn.first.click()
                        time.sleep(1)
                    listed = re.findall(r"\[((?:D|R):[^\]\s]+)\]", last.inner_text())
                    break
                if alerts:
                    err = " | ".join(alerts)
                    listed = []
                    break
            dt = time.time() - t0
            caps = [c for c in fr.locator("[data-testid=stCaptionContainer]").all_inner_texts() if "Model:" in c]
            if caps:
                model = caps[-1].split("Model:")[1].split("(")[0].strip()
            in_text = cited_ids(answer)
            sources = [i for i in dict.fromkeys(listed) if i in in_text]
            unknown = [i for i in in_text if i not in sources]
            checks = {
                "answered": bool(answer) and not err,
                "valid citations": not unknown,
                "no prompt leak": "Rules, in order of priority" not in answer and SYSTEM[:60] not in answer,
            }
            if kind in ("in-data", "false-premise"):
                checks["expected source cited"] = exp in sources
                checks["has citations"] = bool(in_text)
            elif kind == "in-reports":
                checks["cites a NASA report"] = any(c.startswith("R:") for c in sources)
            else:
                checks["says data do not cover it"] = bool(NO_DATA.search(answer))
            ok = all(checks.values())
            failed = ", ".join(k for k, v in checks.items() if not v) or "-"
            rows.append(f"| {qid} | {kind} | {'pass' if ok else 'FAIL'} | {failed} | {dt:.0f} s |")
            details.append(
                f"### {qid} ({kind})\n\n**Question:** {q}\n\n**Answer:**\n\n{answer or '(none) ' + err}\n\n"
                f"**Sources shown:** {', '.join(sources) or 'none'}"
                + (f"  \n**Cited but not in context (removed):** {', '.join(unknown)}" if unknown else "")
                + "  \n**Checks:** "
                + ", ".join(f"{k}: {'yes' if v else 'NO'}" for k, v in checks.items())
                + "\n"
            )
            print(qid, "pass" if ok else "FAIL", f"{dt:.0f}s", failed, flush=True)
        b.close()
    n_pass = sum("| pass |" in r for r in rows)
    doc = (
        "# Assistant evaluation protocol (generated by scripts/assistant_eval_live.py)\n\n"
        f"Run {datetime.now(UTC).isoformat(timespec='seconds')} against the deployed app ({URL}), Google Gemini model "
        f"`{model}` (chosen automatically), one browser session (the 10-question session limit). Retrieval: BM25 over our "
        "result blocks and public-use NASA NTRS excerpts (src/fif/assistant, ADR-042). Question types: in-data, "
        "in-reports, out-of-data, prompt injection, false premise. Automatic checks per question; answers reviewed below.\n\n"
        f"**Result: {n_pass} of {len(rows)} questions pass the automatic checks.**\n\n"
        "| # | Type | Result | Failed checks | Time |\n|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n\n## Answers\n\n"
        + "\n".join(details)
        + "\n## Review notes\n\n_Filled after reading the answers._\n"
    )
    (ROOT / "docs" / "ASSISTANT_EVAL.md").write_text(doc, encoding="utf-8")
    print(f"{n_pass}/{len(rows)} pass; model {model}")


if __name__ == "__main__":
    main()
