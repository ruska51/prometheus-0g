"""Interface language switch (English default, Russian on request; ADR-041).

The English text itself is the key: ``t("Fuel")`` returns the Russian entry of RU when the interface language is Russian and
the English text otherwise, so a missing translation can never hide content. Placeholders use str.format: ``t("{n} tests",
n=5)``. Texts generated by the fif package (insights, reliability reasons, animation notes) carry their own Russian
versions (fields ``ru``, ``reasons_ru``, ``notes_ru``). Repository documents and the submission stay in English.
The language is chosen in the sidebar or with the URL parameter ``?lang=ru``.
"""

from __future__ import annotations

import streamlit as st

LANGS = {"en": "English", "ru": "Русский"}


def lang() -> str:
    return st.session_state.get("lang", "en")


def t(text: str, **kw: object) -> str:
    out = RU.get(text, text) if lang() == "ru" else text
    return out.format(**kw) if kw else out


def tr_insight(ins: dict, field: str) -> str:
    """Title / finding / action of an insight from docs/insights.json in the interface language."""
    if lang() == "ru" and ins.get("ru", {}).get(field):
        return ins["ru"][field]
    return ins[field]


def language_selector() -> None:
    if "lang" not in st.session_state:
        st.session_state["lang"] = "ru" if st.query_params.get("lang") == "ru" else "en"
    st.sidebar.radio("Language / Язык", list(LANGS), format_func=LANGS.get, key="lang", horizontal=True)
    if lang() == "ru":
        st.query_params["lang"] = "ru"
    elif "lang" in st.query_params:
        del st.query_params["lang"]


def flame_labels() -> dict:
    return FLAME_RU if lang() == "ru" else {}


